#!/usr/bin/env node
/**
 * sync-agent-rules.mjs — single source of truth for coding-agent rules.
 *
 * Source (first match wins):
 *   1. AGENTS.md   — the cross-agent standard (agents.md)
 *   2. CLAUDE.md   — legacy fallback
 *
 * Extracts the always-on guardrail section and fans it out to:
 *   - Cursor:   .cursor/rules/coding-guardrails.mdc   (current .mdc format, alwaysApply)
 *   - Cline:    .clinerules/coding-guardrails.md      (directory format)
 *   - Copilot:  .github/copilot-instructions.md
 *   - Claude/ACOS skill: .claude/skills/coding-guardrails/SKILL.md
 *   - Legacy:   .cursorrules + .clinerules single files (--legacy only)
 *
 * Modes:
 *   node scripts/sync-agent-rules.mjs            # write all current targets
 *   node scripts/sync-agent-rules.mjs --legacy   # also write deprecated single-file formats
 *   node scripts/sync-agent-rules.mjs --check    # CI mode: exit 1 if any target is stale
 */

import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const ROOT = process.cwd();
const CHECK = process.argv.includes('--check');
const LEGACY = process.argv.includes('--legacy');

const SECTION_MARKER = '## LLM Behavioral Guardrails';
const GENERATED_NOTICE =
  '<!-- GENERATED by agentic-ops-hub sync-agent-rules.mjs — edit AGENTS.md, not this file -->';

function findSource() {
  for (const name of ['AGENTS.md', 'CLAUDE.md']) {
    const p = path.join(ROOT, name);
    if (fs.existsSync(p)) return { name, path: p };
  }
  return null;
}

function extractRules(content) {
  const start = content.indexOf(SECTION_MARKER);
  if (start === -1) return null;
  const rest = content.slice(start);
  const sep = rest.indexOf('\n---');
  return (sep === -1 ? rest : rest.slice(0, sep)).trim();
}

function targets(rules) {
  const skill = `---
name: coding-guardrails
description: "Unified coding rules and execution loop: thinking protocols, scoped changes, verification, red-team handoff. Triggers on: code rules, guardrails, coding guidelines, conventions, coding style, agent loop."
---

${GENERATED_NOTICE}

# Coding Guardrails

${rules}
`;

  const mdc = `---
description: Unified coding guardrails and execution loop — synced from AGENTS.md
alwaysApply: true
---

${GENERATED_NOTICE}

${rules}
`;

  const md = (title) => `${GENERATED_NOTICE}\n\n# ${title}\n\n${rules}\n`;

  const out = [
    ['.cursor/rules/coding-guardrails.mdc', mdc],
    ['.clinerules/coding-guardrails.md', md('Cline Rules — Unified Coding Guardrails')],
    ['.github/copilot-instructions.md', md('Copilot Instructions — Unified Coding Guardrails')],
    ['.claude/skills/coding-guardrails/SKILL.md', skill],
  ];
  if (LEGACY) {
    out.push(['.cursorrules', md('Cursor Rules (legacy) — Unified Coding Guardrails')]);
  }
  return out;
}

function run() {
  const source = findSource();
  if (!source) {
    console.error('❌ No AGENTS.md or CLAUDE.md found in', ROOT);
    process.exit(1);
  }

  const rules = extractRules(fs.readFileSync(source.path, 'utf8'));
  if (!rules) {
    console.error(`❌ Section "${SECTION_MARKER}" not found in ${source.name}`);
    process.exit(1);
  }

  console.log(`📖 Source of truth: ${source.name}`);
  let stale = 0;

  for (const [rel, content] of targets(rules)) {
    const dest = path.join(ROOT, rel);
    const current = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : null;

    if (CHECK) {
      if (current !== content) {
        console.error(`✗ stale: ${rel}`);
        stale++;
      } else {
        console.log(`✓ fresh: ${rel}`);
      }
      continue;
    }

    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, content);
    console.log(`✅ ${rel}`);
  }

  if (CHECK) {
    if (stale > 0) {
      console.error(`\n${stale} target(s) out of sync. Run: node scripts/sync-agent-rules.mjs`);
      process.exit(1);
    }
    console.log('\nAll targets in sync.');
    return;
  }

  const statusScript = path.join(ROOT, 'scripts', 'acos-status.mjs');
  if (fs.existsSync(statusScript)) {
    try {
      execSync(`node "${statusScript}"`, { stdio: 'inherit' });
    } catch (e) {
      console.error('⚠️  acos-status.mjs failed:', e.message);
    }
  }

  console.log('🎉 Agent rules synchronized.');
}

run();
