#!/usr/bin/env node
// Handover lifecycle for this hub: one file per handover under ops/handovers/, with the index table in
// ops/HANDOVER-INDEX.md and the pickup list in ops/NEXT-PROMPTS.md generated from those files.
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, statSync } from 'node:fs';
import { join, resolve, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const STATUSES = ['open', 'open-unverified', 'claimed', 'processing', 'processed', 'archived', 'superseded', 'abandoned'];
const LIVE = new Set(['open', 'open-unverified', 'claimed', 'processing']);
const FIELDS = ['id', 'what', 'where', 'owner', 'status', 'note', 'supersedes', 'superseded_by', 'evidence', 'updated'];
const INDEX_START = '<!-- handover-index:start -->';
const INDEX_END = '<!-- handover-index:end -->';
const MAX_PROMPT_FILE_LINES = 300;
const MAX_SECTION_LINES = 60;

export function paths(root) {
  return {
    dir: join(root, 'ops', 'handovers'),
    index: join(root, 'ops', 'HANDOVER-INDEX.md'),
    prompts: join(root, 'ops', 'NEXT-PROMPTS.md'),
    archive: join(root, 'ops', 'archive', 'prompts'),
  };
}

export function parseHandover(text) {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) throw new Error('missing frontmatter');
  const meta = {};
  for (const line of match[1].split(/\r?\n/)) {
    const at = line.indexOf(':');
    if (at > 0) meta[line.slice(0, at).trim()] = line.slice(at + 1).trim();
  }
  return { meta, body: match[2] };
}

export function renderHandover({ meta, body }) {
  const head = FIELDS.filter((k) => meta[k]).map((k) => `${k}: ${meta[k]}`);
  return `---\n${head.join('\n')}\n---\n${body ?? ''}`;
}

export function loadAll(root) {
  const { dir } = paths(root);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.md'))
    .map((file) => ({ file, ...parseHandover(readFileSync(join(dir, file), 'utf8')) }));
}

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

export function renderIndexTable(handovers) {
  const rows = [...handovers]
    .sort((a, b) => a.meta.id.localeCompare(b.meta.id))
    .map(({ meta }) => {
      const status = [meta.status, meta.superseded_by && `by ${meta.superseded_by}`, meta.note].filter(Boolean).join('; ');
      return `| [${meta.id}](handovers/${meta.id}.md) | ${cell(meta.what)} | ${cell(meta.where)} | ${cell(meta.owner)} | ${cell(status)} |`;
    });
  return ['| Id | What | Where | Owner | Status |', '|---|---|---|---|---|', ...rows].join('\n');
}

export function renderPrompts(handovers) {
  const live = handovers
    .filter(({ meta, body }) => LIVE.has(meta.status) && /^## Prompt\b/m.test(body))
    .sort((a, b) => (b.meta.updated ?? '').localeCompare(a.meta.updated ?? '') || a.meta.id.localeCompare(b.meta.id));
  const rows = live.map(({ meta }) => `| [${meta.id}](handovers/${meta.id}.md) | ${cell(meta.what)} | ${cell(meta.owner)} | ${meta.status} |`);
  return [
    '# Next prompts',
    '',
    'Generated by `node scripts/handover.mjs index` from `ops/handovers/*.md`. Edit a handover file, never this list.',
    'Each pickup prompt lives in its handover file under `## Prompt`. Rules and lifecycle: [HANDOVER-INDEX.md](HANDOVER-INDEX.md).',
    'Sections retired on 17 October 2026 are kept verbatim in [archive/prompts/](archive/prompts/).',
    '',
    '| Handover | Pickup | Owner | Status |',
    '|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

export function spliceIndex(indexText, table) {
  const start = indexText.indexOf(INDEX_START);
  const end = indexText.indexOf(INDEX_END);
  if (start < 0 || end < start) throw new Error(`HANDOVER-INDEX.md lacks ${INDEX_START} / ${INDEX_END} markers`);
  return `${indexText.slice(0, start + INDEX_START.length)}\n${table}\n${indexText.slice(end)}`;
}

export function regenerate(root) {
  const p = paths(root);
  const all = loadAll(root);
  writeFileSync(p.index, spliceIndex(readFileSync(p.index, 'utf8'), renderIndexTable(all)));
  writeFileSync(p.prompts, renderPrompts(all));
  return all.length;
}

function sectionLengths(text) {
  const lines = text.split(/\r?\n/);
  const out = [];
  let current = null;
  let fenced = false;
  lines.forEach((line, i) => {
    if (/^\s*(```|~~~)/.test(line)) fenced = !fenced;
    if (!fenced && /^#{1,2} /.test(line)) {
      current = { heading: line, start: i + 1, length: 0 };
      out.push(current);
    } else if (current) current.length += 1;
  });
  return out;
}

export function lint(root) {
  const p = paths(root);
  const errors = [];
  const all = loadAll(root);
  const ids = new Set();
  for (const { file, meta } of all) {
    if (!meta.id) { errors.push(`${file}: no id`); continue; }
    if (`${meta.id}.md` !== file) errors.push(`${file}: id ${meta.id} does not match file name`);
    if (ids.has(meta.id)) errors.push(`${file}: duplicate id ${meta.id}`);
    ids.add(meta.id);
    if (!STATUSES.includes(meta.status)) errors.push(`${meta.id}: status "${meta.status}" not in ${STATUSES.join(', ')}`);
    if (meta.status === 'processed' && !meta.evidence) errors.push(`${meta.id}: processed without an evidence link`);
    if (meta.evidence && !isEvidence(root, meta.evidence)) errors.push(`${meta.id}: evidence "${meta.evidence}" is neither an http(s) URL nor a path in this repository`);
    if (meta.status === 'superseded' && !meta.superseded_by) errors.push(`${meta.id}: superseded without superseded_by`);
  }
  for (const { meta } of all) {
    if (meta.superseded_by && !ids.has(meta.superseded_by)) errors.push(`${meta.id}: superseded_by ${meta.superseded_by} has no file`);
  }

  const index = readFileSync(p.index, 'utf8');
  try {
    if (spliceIndex(lf(index), renderIndexTable(all)) !== lf(index)) errors.push('HANDOVER-INDEX.md table is stale: run `node scripts/handover.mjs index`');
  } catch (e) { errors.push(e.message); }

  const prompts = readFileSync(p.prompts, 'utf8');
  if (lf(prompts) !== renderPrompts(all)) errors.push('NEXT-PROMPTS.md is stale or hand-edited: run `node scripts/handover.mjs index`');
  const lineCount = prompts.split(/\r?\n/).length;
  if (lineCount > MAX_PROMPT_FILE_LINES) errors.push(`NEXT-PROMPTS.md has ${lineCount} lines (max ${MAX_PROMPT_FILE_LINES})`);
  checkSections('NEXT-PROMPTS.md', prompts, errors);
  for (const { file, body } of all) checkSections(`handovers/${file}`, body, errors);
  return errors;
}

const lf = (s) => s.replace(/\r\n/g, '\n');

function checkSections(label, text, errors) {
  const seen = new Map();
  for (const s of sectionLengths(text)) {
    if (s.length > MAX_SECTION_LINES) errors.push(`${label}:${s.start} section "${s.heading}" is ${s.length} lines (max ${MAX_SECTION_LINES})`);
    if (seen.has(s.heading)) errors.push(`${label}:${s.start} repeats heading from line ${seen.get(s.heading)}: ${s.heading}`);
    else seen.set(s.heading, s.start);
  }
}

export function setStatus(root, id, status, { evidence, by, owner, note, today } = {}) {
  if (!STATUSES.includes(status)) throw new Error(`unknown status ${status}`);
  const file = join(paths(root).dir, `${id}.md`);
  if (!existsSync(file)) throw new Error(`no handover ${id}`);
  const h = parseHandover(readFileSync(file, 'utf8'));
  const meta = { ...h.meta, status, updated: today ?? isoDate() };
  if (evidence !== undefined) meta.evidence = evidence;
  if (by) meta.superseded_by = by;
  if (owner) meta.owner = owner;
  if (note !== undefined) meta.note = note;
  if (meta.evidence !== undefined && !isEvidence(root, meta.evidence)) throw new Error(`evidence "${meta.evidence}" is neither an http(s) URL nor a path in this repository`);
  if (status === 'processed' && !meta.evidence) throw new Error('processed needs evidence: a merged PR, receipt or issue comment URL');
  writeFileSync(file, renderHandover({ meta, body: h.body }));
}

export function isEvidence(root, v) {
  if (!v) return false;
  if (/^[a-z][a-z0-9+.-]*:/i.test(v)) {
    try {
      const url = new URL(v);
      return (url.protocol === 'https:' || url.protocol === 'http:') && url.hostname.length > 0;
    } catch { return false; }
  }
  const base = resolve(root);
  const target = resolve(base, v);
  return target.startsWith(base + sep) && existsSync(target) && statSync(target).isFile();
}

export function create(root, meta, body = '') {
  const { dir } = paths(root);
  mkdirSync(dir, { recursive: true });
  const file = join(dir, `${meta.id}.md`);
  if (existsSync(file)) throw new Error(`handover ${meta.id} already exists`);
  writeFileSync(file, renderHandover({ meta: { status: 'open', updated: isoDate(), ...meta }, body }));
}

const isoDate = () => new Date().toISOString().slice(0, 10);

const FLAGS = {
  new: ['what', 'where', 'owner', 'status', 'body'],
  claim: ['owner'],
  process: ['evidence'],
  supersede: ['by'],
  status: ['note', 'evidence'],
  index: [],
  lint: [],
};

// Every flag takes a value; a value that itself begins with -- must use the --flag=value form.
export function parseArgs(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (!arg.startsWith('--')) { out._.push(arg); continue; }
    const eq = arg.indexOf('=');
    const key = eq > 0 ? arg.slice(2, eq) : arg.slice(2);
    if (eq > 0) { out[key] = arg.slice(eq + 1); continue; }
    if (argv[i + 1] === undefined || argv[i + 1].startsWith('--')) throw new Error(`--${key} needs a value (use --${key}=<value> for a value starting with --)`);
    out[key] = argv[++i];
  }
  const allowed = FLAGS[out._[0]];
  if (allowed) for (const key of Object.keys(out)) if (key !== '_' && !allowed.includes(key)) throw new Error(`${out._[0]} does not take --${key}`);
  return out;
}

const USAGE = `usage: node scripts/handover.mjs <command>
  new <id> --what <text> --where <text> --owner <harness> [--status open]
  claim <id> --owner <harness>          status -> claimed
  process <id> --evidence <url>         status -> processed (evidence required)
  supersede <id> --by <other-id>        status -> superseded
  status <id> <status> [--note <text>]  any status in: ${STATUSES.join(', ')}
  index                                 regenerate HANDOVER-INDEX table and NEXT-PROMPTS.md
  lint                                  exit 1 on stale index, oversized or repeated prompt sections, missing evidence`;

function main(argv) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const a = parseArgs(argv);
  const [cmd, id, extra] = a._;
  if (FLAGS[cmd] && !['index', 'lint'].includes(cmd) && !id) throw new Error(`${cmd} needs a handover id`);
  switch (cmd) {
    case 'new':
      create(root, { id, what: a.what, where: a.where, owner: a.owner, status: a.status ?? 'open' }, a.body ? `\n${a.body}\n` : '');
      break;
    case 'claim':
      if (!a.owner) throw new Error('claim needs --owner <harness>');
      setStatus(root, id, 'claimed', { owner: a.owner }); break;
    case 'process':
      if (!a.evidence) throw new Error('process needs --evidence <merged PR, receipt or issue comment URL>');
      setStatus(root, id, 'processed', { evidence: a.evidence }); break;
    case 'supersede':
      if (!a.by) throw new Error('supersede needs --by <id>');
      setStatus(root, id, 'superseded', { by: a.by }); break;
    case 'status': setStatus(root, id, extra, { note: a.note, evidence: a.evidence }); break;
    case 'index': console.log(`indexed ${regenerate(root)} handovers`); return 0;
    case 'lint': {
      const errors = lint(root);
      errors.forEach((e) => console.error(`handover lint: ${e}`));
      if (!errors.length) console.log('handover lint: ok');
      return errors.length ? 1 : 0;
    }
    default: console.error(USAGE); return 2;
  }
  regenerate(root);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { process.exitCode = main(process.argv.slice(2)); } catch (e) { console.error(`handover: ${e.message}`); process.exitCode = 2; }
}
